def uc(id, title, actors, pre, post, flow, screens, refs, status='code-inferred', alt=None):
    return dict(id=id, title=title, actors=actors, preconditions=pre, postconditions=post, mainFlow=flow,
                alternativeFlows=alt or [], screens=screens, odooRefs=refs, status=status, reviewStatus='pending')


def mf(name, purpose, params, returns, pattern, refs, calls=(), validations=(), hidden=(), kind='Microflow'):
    return dict(name=name, kind=kind, purpose=purpose, params=params, returns=returns, pattern=pattern,
                calls=list(calls), validations=list(validations), hiddenRules=list(hidden), odooRefs=refs)


def pg(name, purpose, ctx, sections, actions, refs, pattern='form'):
    return dict(name=name, purpose=purpose, dataContext=ctx, pattern=pattern, sections=sections, actions=actions,
                layout='Atlas_Core.Atlas_Default', odooRefs=refs)


